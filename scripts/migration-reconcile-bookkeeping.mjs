#!/usr/bin/env node
/**
 * RECONCILE THE MIGRATION BOOKKEEPING — record what the schema proves was applied.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * THE PROBLEM, MEASURED
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * 25 Aug 2026, live `lawmind`:
 *
 *     _journal.json entries                   87
 *     drizzle.__drizzle_migrations rows       58
 *     newest recorded created_at              1786442900000  = journal idx 72
 *
 * Twenty-nine migrations were applied by executing their SQL directly instead of
 * through `migrate()`. `migration-truth.mjs` confirms all twenty-nine against the
 * catalogues: every object each one declares is present.
 *
 * Drizzle does not count rows — it advances on the newest recorded `created_at`.
 * So the live cursor sits at idx 72 and `migrate()` believes fourteen migrations
 * are pending that are already applied. All fourteen happen to be idempotent, so
 * today it would succeed noisily rather than fail. **That is luck, not design.**
 * The next hand-applied migration that is not idempotent turns a no-op into an
 * aborted release, and the abort lands halfway through.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY RECORDING IS THE SAFE DIRECTION AND RE-RUNNING IS NOT
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Two repairs were available.
 *
 *   Re-run the official migrate path against live, and let it write its own rows.
 *   Rejected: it re-executes 29 migrations against a database holding 18.7M
 *   judgments to fix a bookkeeping table. Every one is a chance to do real harm
 *   in service of a cosmetic fix, and R7 §8 says in terms not to run migrate
 *   blindly on the live DB.
 *
 *   Record the rows that are missing. Chosen: it touches no schema, no data and
 *   no index. The only thing that can go wrong is recording a migration that is
 *   NOT applied — which would make it skipped forever — so that is the one thing
 *   this refuses to do, and it refuses by evidence rather than by trust.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * THE REFUSAL
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * A row is written only for a migration whose status in a FRESHLY REGENERATED
 * manifest is `APPLIED_UNRECORDED` — meaning every table, column, index,
 * constraint, view, enum and function it declares was found in the live
 * catalogues. `PARTIALLY_APPLIED`, `JOURNALLED_UNAPPLIED` and `UNKNOWN` are
 * skipped and named.
 *
 * The manifest is regenerated by this script rather than read from disk. A stale
 * manifest is exactly the failure that cost NEW1 65 GPU-minutes: a worklist file
 * faithfully re-read and never re-measured. Reading a saved manifest here would
 * repeat it, with a worse consequence.
 *
 * Usage:
 *   node scripts/migration-reconcile-bookkeeping.mjs            dry run (default)
 *   node scripts/migration-reconcile-bookkeeping.mjs --apply    write the rows
 */

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APPLY = process.argv.includes('--apply');

function databaseUrl() {
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL.trim();
  const m = readFileSync(join(REPO, '.env'), 'utf8').match(/^DATABASE_URL=(.+)$/m);
  if (!m) throw new Error('no DATABASE_URL');
  return m[1].trim();
}

async function main() {
  console.log('regenerating the migration manifest against the live database...');
  const raw = execFileSync(process.execPath, [join(REPO, 'scripts', 'migration-truth.mjs'), '--json'], {
    cwd: REPO,
    encoding: 'utf8',
    timeout: 5 * 60 * 1000,
    maxBuffer: 64 * 1024 * 1024,
  });
  const manifest = JSON.parse(raw);

  const recordable = manifest.migrations.filter((m) => m.status === 'APPLIED_UNRECORDED');
  const refused = manifest.migrations.filter(
    (m) => !m.bookkeeping && m.status !== 'APPLIED_UNRECORDED',
  );

  console.log('');
  console.log(`journal ${manifest.journal_entries} · bookkeeping rows ${manifest.bookkeeping_rows}`);
  console.log(`drizzle cursor: "${manifest.drizzle_cursor_tag}"`);
  console.log('');
  console.log(`WOULD RECORD ${recordable.length} migration(s) whose every declared object is present:`);
  for (const m of recordable) {
    console.log(`  ${String(m.idx).padStart(3)} ${m.tag.padEnd(44)} ${m.objects_present}/${m.objects_declared} objects present`);
  }
  if (refused.length) {
    console.log('');
    console.log(`REFUSING ${refused.length} — the schema does not prove these were applied:`);
    for (const m of refused) {
      console.log(`  ${String(m.idx).padStart(3)} ${m.tag.padEnd(44)} ${m.status}  missing: ${m.objects_missing.join(', ') || '(none declared)'}`);
    }
  }

  if (!recordable.length) {
    console.log('\nnothing to record — bookkeeping already agrees with the schema.');
    return;
  }

  if (!APPLY) {
    console.log('\nDRY RUN. Nothing was written. Re-run with --apply to record these rows.');
    return;
  }

  const { default: postgres } = await import(
    '../services/ingest/node_modules/postgres/src/index.js'
  );
  const sql = postgres(databaseUrl(), { max: 1, onnotice: () => {} });
  try {
    // One transaction. A half-written bookkeeping table is worse than an
    // unwritten one: it moves the cursor partway and makes the next `migrate()`
    // skip migrations that were never recorded and never applied.
    const written = await sql.begin(async (tx) => {
      const rows = [];
      for (const m of recordable) {
        // `created_at` MUST be the journal's `when`, not now(). It is the cursor
        // drizzle compares against, and stamping it with the current time would
        // put every recorded migration ahead of every future one and make the
        // next real migration invisible to the migrator.
        const r = await tx`
          INSERT INTO drizzle.__drizzle_migrations (hash, created_at)
          VALUES (${m.hash}, ${m.when})
          RETURNING id`;
        rows.push({ tag: m.tag, id: r[0].id });
      }
      return rows;
    });

    console.log('');
    for (const r of written) console.log(`  recorded ${r.tag} as id ${r.id}`);

    const after = await sql`SELECT count(*)::int AS n, max(created_at)::bigint AS newest
      FROM drizzle.__drizzle_migrations`;
    console.log('');
    console.log(`bookkeeping rows now ${after[0].n}, newest created_at ${after[0].newest}`);

    const journal = JSON.parse(
      readFileSync(join(REPO, 'packages', 'db', 'drizzle', 'meta', '_journal.json'), 'utf8'),
    );
    const pending = journal.entries.filter((e) => e.when > Number(after[0].newest));
    console.log(
      pending.length === 0
        ? 'migrate() against this database is now a NO-OP: 0 journal entries above the cursor.'
        : `migrate() would still apply ${pending.length}: ${pending.map((e) => e.tag).join(', ')}`,
    );
  } finally {
    await sql.end({ timeout: 5 });
  }
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 2;
});
