// modes
// ─────────────────────────────────────────────────────────────────────────────
const RESTORE_SETTINGS = {
  // Every byte is reproducible from the archive on disk during a restore, so
  // fsync-per-commit buys nothing and costs hours.
  synchronous_commit: 'off',
  // Autovacuum during a bulk load competes for exactly the IO the load needs,
  // and vacuums tables that are about to grow tenfold. ANALYZE runs once at the
  // end instead — see restore.mjs.
  autovacuum: 'off',
  // Bulk COPY generates WAL faster than any normal workload.
  max_wal_size: '32GB',
  checkpoint_timeout: '60min',
  // pg_restore --jobs workers each build indexes; give them room — but this is
  // PER WORKER, and this machine's binding constraint is the Windows commit
  // limit, not RAM (see lawmind.conf, shared_buffers). 4 jobs x 1 GB = 4 GB.
  maintenance_work_mem: '1GB',
};

const SERVE_SETTINGS = {
  synchronous_commit: 'on',
  autovacuum: 'on',
  max_wal_size: '16GB',
  checkpoint_timeout: '30min',
  maintenance_work_mem: '512MB',
};

function applySettings(map, label) {
  for (const [k, v] of Object.entries(map)) {
    psqlExec(`ALTER SYSTEM SET ${k} = '${v}'`);
  }
  psqlExec('SELECT pg_reload_conf()');
  console.log(`${label}: applied ${Object.keys(map).length} settings via ALTER SYSTEM + reload`);
  // Two of these need a restart to take effect; say which rather than leaving
  // the caller to discover it from a value that did not change.
  console.log(`${label}: note — shared_buffers-class settings need a restart; these do not.`);
  for (const k of Object.keys(map)) {
    console.log(`  ${k} = ${psqlValue(`SHOW ${k}`)}`);
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// createdb
// ─────────────────────────────────────────────────────────────────────────────
function createTargetDb() {
  const exists = psqlValue(`SELECT 1 FROM pg_database WHERE datname = '${PG.database}'`);
  if (exists === '1') {
    console.log(`createdb: ${PG.database} already exists`);
  } else {
    // ICU en-US, matching the reasoning in lawmind.conf: the source is libc
    // en_US.utf8, which does not exist on Windows, and the schema names no
    // collation explicitly so nothing in the dump depends on the old name.
    run(exe('createdb'), [
      '--encoding=UTF8',
      '--locale-provider=icu',
      '--icu-locale=en-US',
      '--template=template0',
      PG.database,
    ]);
    console.log(`createdb: created ${PG.database}`);
  }

  // The three extensions the source carries, at the source's versions where the
  // local build allows it. pg_restore would create them itself from the dump,
  // but doing it here means a missing extension fails NOW — before a six-hour
  // restore — instead of as one skipped line inside it.
  for (const ext of ['pg_trgm', 'vector']) {
    try {
      psqlExec(`CREATE EXTENSION IF NOT EXISTS ${ext}`, PG.database);
      const v = psqlValue(`SELECT extversion FROM pg_extension WHERE extname='${ext}'`, PG.database);
      console.log(`createdb: extension ${ext} ${v}`);
    } catch (e) {
      console.error(`createdb: EXTENSION ${ext} FAILED — ${String(e.message).split('\n')[0]}`);
      console.error(`  This is a stop, not a warning. The source uses it and a restore without it`);
      console.error(`  produces a database that is missing columns, not one that is merely slower.`);
      process.exitCode = 1;
    }
  }
}

// ─────────────────────────────────────────────────────────────────────────────
function status() {
  console.log(`bin      ${PG.bin}`);
  console.log(`data     ${PG.data}`);
  console.log(`port     ${PG.port}`);
  console.log(`running  ${isRunning()}`);
  if (!isRunning()) return;
  console.log(`version  ${psqlValue('SHOW server_version')}`);
  for (const k of ['shared_buffers', 'work_mem', 'maintenance_work_mem', 'synchronous_commit', 'autovacuum', 'max_wal_size', 'listen_addresses']) {
    console.log(`  ${k.padEnd(22)} ${psqlValue(`SHOW ${k}`)}`);
  }
  const dbs = psqlValue(
    `SELECT string_agg(datname || ' (' || pg_size_pretty(pg_database_size(datname)) || ')', ', ' ORDER BY datname)
     FROM pg_database WHERE datistemplate = false`,
  );
  console.log(`  databases              ${dbs}`);
}

function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  switch (cmd) {
    case 'configure':
      return configure();
    case 'start':
      return start();
    // Used by the LawMindPostgres scheduled task. Spawns and exits immediately:
    // the postmaster is detached, so the launcher's lifetime is irrelevant to
    // it, and a task that lingers waiting to report readiness is a task that can
    // be killed for lingering.
    case 'spawn-detached': {
      if (isRunning()) {
        console.log('spawn-detached: already running');
        return;
      }
      console.log(`spawn-detached: pid ${spawnPostmaster()}`);
      return;
    }
    case 'stop':
      return stop();
    case 'restart':
      stop();
      return start();
    case 'status':
      return status();
    case 'restore-mode':
      return applySettings(RESTORE_SETTINGS, 'restore-mode');
    case 'serve-mode':
      return applySettings(SERVE_SETTINGS, 'serve-mode');
    case 'createdb':
      return createTargetDb();
    case 'psql': {
      const r = run(exe('psql'), ['-d', PG.database, ...rest]);
      process.exit(r.status ?? 1);
      break;
    }
    default:
      console.log(
        'usage: pg-local.mjs configure|start|stop|restart|status|restore-mode|serve-mode|createdb|psql [args]',
      );
      process.exit(2);
  }
}

if (process.argv[1]?.endsWith('pg-local.mjs')) main();
