#!/usr/bin/env node
/**
 * Repair a restored database whose GENERATED columns were dropped to load the
 * dump, and put them back WITHOUT moving the column.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY THIS EXISTS AT ALL
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * `SELECT *` includes a STORED generated column, `COPY <table> FROM` with no
 * column list excludes it, so the chunked archives carry one field more than a
 * plain restore expects:
 *
 *   ERROR:  row field count is 33, expected 32   (judgments.full_text_tsv)
 *
 * The first attempt at a fix used `ALTER COLUMN ... DROP EXPRESSION` to load,
 * intending to re-attach the expression afterwards. **There is no way back.**
 * `SET EXPRESSION AS` only replaces the expression of a column that is already
 * generated, and no `ADD GENERATED` exists for a plain column. `DROP COLUMN` +
 * `ADD COLUMN ... GENERATED` works and moves the column to the END of the
 * table — and column order is exactly what a `COPY` without a column list
 * depends on, so it would then disagree with the Drizzle migrations.
 *
 * `restore-chunked.mjs` no longer gets into this state: it stages the load
 * through a `LIKE` clone (EXCLUDING GENERATED by default) and never alters the
 * real table. This script is for a database already stranded in it — the table
 * is rebuilt with DDL taken verbatim from the schema archive, so the generated
 * column returns to its original ordinal position.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * PARALLEL, AND RESUMABLE ACROSS A POWER CUT
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * Recomputing `to_tsvector` over 7.3M judgments is CPU-bound and single-threaded
 * per connection. One `INSERT ... SELECT` ran for 40 minutes and had not
 * finished when the machine lost power; the whole transaction rolled back. So
 * the copy is split into id ranges run concurrently, each its OWN transaction.
 *
 * Progress is recorded by inserting a marker row into `__regen_ranges` **inside
 * the same transaction as the range's rows**. That is the only way the record
 * cannot disagree with reality: a crash either commits both or neither. A JSON
 * progress file would have a window between COMMIT and the file write in which
 * a crash makes a finished range look unfinished — and re-running it would
 * duplicate rows into a table that has no primary key yet, because post-data
 * has not run.
 *
 *   node scripts/migration/regenerate-generated-columns.mjs --status
 *   node scripts/migration/regenerate-generated-columns.mjs --run [--jobs 8]
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
import { PG, pgEnv, psqlValue, psqlExec } from './pg-local.mjs';

const SCHEMA_ARCHIVE = path.join(PG.dump, 'schema');
const exe = (n) => path.join(PG.bin, `${n}.exe`);
const SPLITS = 32;

/** Tables this repair knows how to rebuild, discovered from the archive. */
const TARGETS = ['judgments', 'statute_sections'];

/**
 * The CREATE TABLE comes from the schema archive, never from memory and never
 * from the live catalogue — the live one is precisely what is damaged.
 * PRIMARY KEY / UNIQUE / FK / indexes are absent on purpose: pg_dump puts those
 * in post-data, which runs afterwards and will add them.
 */
function ddlFromArchive(table) {
  const r = spawnSync(
    exe('pg_restore'),
    ['--section=pre-data', '-t', table, '-f', '-', SCHEMA_ARCHIVE],
    { env: pgEnv(), encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  const m = r.stdout.match(new RegExp(`CREATE TABLE public\\.${table} \\([\\s\\S]*?\\n\\);`));
  if (!m) {
    console.error(`could not extract CREATE TABLE public.${table} from ${SCHEMA_ARCHIVE}`);
    process.exit(2);
  }
  return m[0];
}

function columnsOf(table, { generated }) {
  return psqlValue(
    `SELECT string_agg(column_name, ', ' ORDER BY ordinal_position)
       FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = '${table}'
        AND is_generated ${generated ? '<>' : '='} 'NEVER'`,
    PG.database,
  ).trim();
}

const exists = (t) =>
  psqlValue(
    `SELECT count(*) FROM information_schema.tables
      WHERE table_schema='public' AND table_name='${t}'`,
    PG.database,
  ).trim() === '1';

const isGenerated = (t, c) =>
  psqlValue(
    `SELECT count(*) FROM information_schema.columns
      WHERE table_schema='public' AND table_name='${t}' AND column_name='${c}'
        AND is_generated <> 'NEVER'`,
    PG.database,
  ).trim() === '1';

/**
 * Split by PHYSICAL position (`ctid`), not by the uuid key.
 *
 * The obvious split is equal hex ranges over `id`, the way the dump splits. It
 * is wrong here: post-data has not run, so the stage table has **no indexes at
 * all** — every `WHERE id BETWEEN ...` is a full sequential scan, and 32 of
 * them would read the heap 32 times over.
 *
 * A `ctid` range gives each worker a disjoint PHYSICAL slice, so the heap is
 * read exactly once in total (PostgreSQL 14+ plans this as a Tid Range Scan).
 * Safe only because the stage table is read-only for the duration — a `ctid` is
 * a row's current location, not a stable identity, and this is the one
 * situation where relying on it is sound.
 *
 * Sized from the main fork only. On `judgments` that is 7.7 GB of heap against
 * 43 GB of TOAST: the text is fetched per row through the TOAST index either
 * way, and no partitioning scheme changes that.
 */
function ranges(splits, pages) {
  const out = [];
  const per = Math.ceil(pages / splits);
  for (let i = 0; i < splits; i++) {
    const lo = i * per;
    const hi = i === splits - 1 ? null : (i + 1) * per;
    out.push({
      i,
      where:
        hi === null
          ? `ctid >= '(${lo},0)'::tid`
          : `ctid >= '(${lo},0)'::tid AND ctid < '(${hi},0)'::tid`,
    });
  }
  return out;
}

function runRange(table, stage, cols, r) {
  // One transaction: the rows and the marker that says the rows are there.
  const sql = `BEGIN;
INSERT INTO public.${table} (${cols}) SELECT ${cols} FROM public.${stage} WHERE ${r.where};
INSERT INTO public.__regen_ranges (tbl, range_index) VALUES ('${table}', ${r.i});
COMMIT;`;
  return new Promise((resolve) => {
    const p = spawn(exe('psql'), ['-d', PG.database, '-X', '-q', '-v', 'ON_ERROR_STOP=1', '-c', sql], {
      env: pgEnv(),
      windowsHide: true,
    });
    let err = '';
    p.stderr.on('data', (d) => (err += d));
    p.stdout.on('data', () => {});
    p.on('close', (code) => resolve({ code, err: err.trim() }));
  });
}

async function rebuild(table, jobs) {
  const gencols = columnsOf(table, { generated: true });
  const stage = `${table}__stage`;

  if (!exists(stage)) {
    if (gencols) {
      console.log(`${table}: already generated (${gencols}) — nothing to do`);
      return true;
    }
    console.log(`${table}: renaming to ${stage} and recreating from the schema archive`);
    psqlExec(`ALTER TABLE public.${table} RENAME TO ${stage}`, PG.database);
    psqlExec(ddlFromArchive(table), PG.database);
  } else {
    console.log(`${table}: resuming — ${stage} already exists`);
    if (!exists(table)) psqlExec(ddlFromArchive(table), PG.database);
  }

  const genNow = columnsOf(table, { generated: true });
  if (!genNow) {
    console.error(`${table}: recreated table still has no generated column — refusing to continue`);
    return false;
  }
  const cols = columnsOf(table, { generated: false });

  psqlExec(
    `CREATE TABLE IF NOT EXISTS public.__regen_ranges
       (tbl text NOT NULL, range_index int NOT NULL, PRIMARY KEY (tbl, range_index))`,
    PG.database,
  );
  const done = new Set(
    (psqlValue(
      `SELECT coalesce(string_agg(range_index::text, ','), '') FROM public.__regen_ranges WHERE tbl='${table}'`,
      PG.database,
    ) || '')
      .split(',')
      .filter(Boolean)
      .map(Number),
  );

  // Page count of the STAGE table — the thing actually being scanned. Read after
  // the rename, so it describes the table the ranges will be applied to.
  const pages = Number(
    psqlValue(`SELECT (pg_relation_size('public.${stage}') / 8192)::bigint + 1`, PG.database).trim(),
  );
  const todo = ranges(SPLITS, pages).filter((r) => !done.has(r.i));
  console.log(`${table}: ${pages} heap pages, split ${SPLITS} ways by ctid`);
  console.log(`${table}: ${done.size}/${SPLITS} ranges already committed, ${todo.length} to go, ${jobs} at a time`);

  let failed = 0;
  let finished = done.size;
  const started = Date.now();
  const queue = [...todo];
  await Promise.all(
    Array.from({ length: Math.min(jobs, queue.length) }, async () => {
      for (;;) {
        const r = queue.shift();
        if (!r) return;
        const t0 = Date.now();
        const res = await runRange(table, stage, cols, r);
        if (res.code !== 0) {
          failed++;
          console.error(`  FAIL range ${r.i} — ${res.err.split('\n').slice(0, 2).join(' | ')}`);
          continue;
        }
        finished++;
        const el = (Date.now() - started) / 1000;
        const rate = (finished - done.size) / el;
        const eta = rate > 0 ? Math.round((SPLITS - finished) / rate) : 0;
        console.log(
          `  ok   range ${String(r.i).padStart(2)}  ${String(Math.round((Date.now() - t0) / 1000)).padStart(4)}s   ` +
            `${finished}/${SPLITS} done · eta ${Math.round(eta / 60)}m`,
        );
      }
    }),
  );

  if (failed) {
    console.error(`${table}: ${failed} range(s) failed — re-run, committed ranges are skipped`);
    return false;
  }

  const src = psqlValue(`SELECT count(*) FROM public.${stage}`, PG.database).trim();
  const dst = psqlValue(`SELECT count(*) FROM public.${table}`, PG.database).trim();
  if (src !== dst) {
    console.error(`${table}: COUNT MISMATCH — ${stage} has ${src}, ${table} has ${dst}. Not dropping the stage.`);
    return false;
  }
  console.log(`${table}: ${dst} rows match the stage exactly — dropping ${stage}`);
  psqlExec(`DROP TABLE public.${stage}`, PG.database);
  psqlExec(`DELETE FROM public.__regen_ranges WHERE tbl='${table}'`, PG.database);
  return true;
}

async function main() {
  const argv = process.argv.slice(2);
  const jobs = argv.includes('--jobs') ? Number(argv[argv.indexOf('--jobs') + 1]) : 8;

  if (argv.includes('--status')) {
    for (const t of TARGETS) {
      const gen = columnsOf(t, { generated: true });
      console.log(
        `${t.padEnd(18)} generated=${gen || 'NONE'}  stage=${exists(`${t}__stage`) ? 'PRESENT' : 'absent'}`,
      );
    }
    return;
  }

  if (!argv.includes('--run')) {
    console.log('usage: regenerate-generated-columns.mjs --status | --run [--jobs 8]');
    return;
  }

  let allOk = true;
  for (const t of TARGETS) {
    if (!exists(t) && !exists(`${t}__stage`)) {
      console.log(`${t}: not present, skipping`);
      continue;
    }
    const ok = await rebuild(t, jobs);
    allOk = allOk && ok;
  }

  // Only tidy the bookkeeping table once every target is genuinely finished.
  if (allOk && exists('__regen_ranges')) {
    const left = psqlValue('SELECT count(*) FROM public.__regen_ranges', PG.database).trim();
    if (left === '0') psqlExec('DROP TABLE public.__regen_ranges', PG.database);
  }

  for (const t of TARGETS) {
    if (exists(t)) {
      const gen = columnsOf(t, { generated: true });
      console.log(`${t}: generated column(s) = ${gen || 'NONE — STILL BROKEN'}`);
    }
  }
  process.exit(allOk ? 0 : 1);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
